class WorkerSignals(QObject):
    finished = pyqtSignal(object)
    error = pyqtSignal(str)
    log = pyqtSignal(str, str)
    progress = pyqtSignal(int)


class WorkerThread(QThread):

    def __init__(self, fn, *args, **kwargs):
        super().__init__()
        self.fn = fn
        self.args = args
        self.kwargs = kwargs
        self.signals = WorkerSignals()

    def run(self):
        try:
            # Inject signals into kwargs if the function accepts them (for progress updates)
            if 'worker_signals' in self.fn.__code__.co_varnames:
                self.kwargs['worker_signals'] = self.signals
            result = self.fn(*self.args, **self.kwargs)
            self.signals.finished.emit(result)
        except Exception as e:
            err_msg = f"CRITICAL CRASH: {str(e)}\n{traceback.format_exc()}"
            self.signals.error.emit(err_msg)


