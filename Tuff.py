    # --- CORE WORKER DISPATCHER ---
    def _dispatch_task(self,
                       func,
                       success_msg="",
                       success_lvl="success",
                       callback=None,
                       *args,
                       **kwargs):
        """Asynchronously dispatches a generic function so the GUI never hangs."""
        thread = WorkerThread(func, *args, **kwargs)

        def on_finished(result):
            if success_msg: self.log_msg(success_msg, success_lvl)
            if callback and result is not None: callback(result)
            thread.deleteLater()

        def on_error(e):
            self.log_msg(e, "error")
            thread.deleteLater()

        thread.signals.finished.connect(on_finished)
        thread.signals.error.connect(on_error)
        thread.signals.log.connect(self.log_msg)

        # Store hard reference to avoid GC
        self._current_thread = thread
        thread.start()

