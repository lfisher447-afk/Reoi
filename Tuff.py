class NeuralFixer:
    """Parses, lints, and physically fixes Roku Brightscript code."""

    def __init__(self, workspace: Path):
        self.workspace = workspace
        self.fixes = 0
        self.logs = []

    def _msg(self, msg):
        self.logs.append(msg)

    def execute_repairs(self):
        if not self.workspace or not self.workspace.exists():
            return "Cannot repair: Workspace invalid."

        self._msg(">>> INITIATING QUANTUM CODEBASE REPAIRS")
        self.fixes = 0

        self.repair_orphaned_xml()

        files = list(self.workspace.rglob("*.bs")) + list(
            self.workspace.rglob("*.brs"))
        for file in files:
            self.repair_script(file)

        self._msg(
            f"\n>>> REMEDIATION COMPLETE. Total Injections/Patches: {self.fixes}"
        )
        return "\n".join(self.logs)

    def repair_orphaned_xml(self):
        comp_dir = self.workspace / "src/components"
        if not comp_dir.exists(): return

        xmls = {f.stem: f for f in comp_dir.rglob("*.xml")}
        bss = {f.stem for f in comp_dir.rglob("*.bs")}
        orphans = set(xmls.keys()) - bss

        for name in orphans:
            new_file = xmls[name].with_suffix(".bs")
            code = f"' === AUTO-GENERATED BY QUANTUM FIXER ===\nsub init()\n    m.top.id = \"{name}\"\nend sub\n"
            new_file.write_text(code)
            self.fixes += 1
            self._msg(
                f"[XML-ORPHAN] Generated missing controller for <{name}.xml>")

    def repair_script(self, filepath: Path):
        try:
            orig = filepath.read_text(encoding="utf-8")
        except:
            return

        fixed = orig

        # 1. Javascript `console.log` -> `print`
        if "console.log" in fixed:
            fixed = re.sub(r'console\.log\((.*?)\)', r'print \1', fixed)
            self._msg(f"[AST-FIX] Cleaned JS console.log in {filepath.name}")
            self.fixes += 1

        # 2. Javascript `let` and `const` -> Implicit declaration
        if re.search(r'\b(?:let|const)\s+[a-zA-Z0-9_]+', fixed):
            fixed = re.sub(r'\b(?:let|const)\s+([a-zA-Z0-9_]+)', r'\1', fixed)
            self._msg(
                f"[AST-FIX] Neutered JS let/const declarations in {filepath.name}"
            )
            self.fixes += 1

        # 3. CreateObject Legacy Syntax -> Modern Syntax
        if 'CreateObject("roArray")' in fixed:
            fixed = re.sub(r'CreateObject\s*\(\s*"roArray"\s*\)', r'[]', fixed)
            self.fixes += 1
        if 'CreateObject("roAssociativeArray")' in fixed:
            fixed = re.sub(r'CreateObject\s*\(\s*"roAssociativeArray"\s*\)',
                           r'{}', fixed)
            self.fixes += 1

        # 4. Strict Memory Leak Patcher (Missing unobserveField)
        observations = set(re.findall(r'(\w+)\.observeField\("([^"]+)"',
                                      fixed))
        for obs_node, obs_field in observations:
            unobs_str = f'{obs_node}.unobserveField("{obs_field}")'
            if unobs_str not in fixed:
                # We inject into a `dispose` or `close` function if exists, else we append
                if re.search(r'sub\s+(?:dispose|close|uninit)\s*\(\)', fixed,
                             re.IGNORECASE):
                    fixed = re.sub(r'(sub\s+(?:dispose|close|uninit)\s*\(\))',
                                   f'\\1\n    {unobs_str} \' Quantum Patch',
                                   fixed,
                                   flags=re.IGNORECASE)
                else:
                    fixed += f"\n\nsub dispose()\n    {unobs_str} ' Quantum Patch\nend sub\n"
                self._msg(
                    f"[MEM-PATCH] Sealed Memory Leak in {filepath.name}: injected unobserveField for '{obs_field}'"
                )
                self.fixes += 1

        if fixed != orig:
            # Backup before writing
            shutil.copy2(filepath, filepath.with_name(filepath.name + ".bak"))
            filepath.write_text(fixed, encoding="utf-8")


