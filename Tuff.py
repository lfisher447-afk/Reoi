    def _gen_changelog(self):
        if not self.engine.workspace: return

        def _job():
            res = self.engine.run_git(
                ["log", "--pretty=format:%ad|%s", "--date=short"])
            out = ["# CHANGELOG\n"]
            history = defaultdict(list)
            for line in res.splitlines():
                if "|" in line:
                    d, m = line.split("|", 1)
                    history[d].append(f"- {m}")
            for d in sorted(history, reverse=True):
                out.append(f"## {d}\n" + "\n".join(history[d]) + "\n")
            cl = self.engine.workspace / "CHANGELOG.md"
            cl.write_text("\n".join(out))
            return f"Synthesized CHANGELOG.md locally at {cl.name}"

        self._dispatch_task(_job,
                            success_lvl="success",
                            callback=lambda r: self.out_git.setText(r))

