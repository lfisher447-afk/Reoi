    def log_msg(self, msg, level="info"):
        cols = {
            "info": "#8b949e",
            "success": "#3fb950",
            "warn": "#d29922",
            "error": "#f85149"
        }
        c = cols.get(level, "#ffffff")
        ts = datetime.now().strftime("%H:%M:%S")

        # Determine prefix based on level
        prefix = "[i]"
        if level == "success": prefix = "[✓]"
        elif level == "warn": prefix = "[!]"
        elif level == "error": prefix = "[✗]"

        formatted = f"<span style='color:#30363d'>[{ts}]</span> <span style='color:{c}; font-weight:bold;'>{prefix}</span> <span style='color:{c}'>{msg}</span>"
        self.terminal.append(formatted)
        self.terminal.moveCursor(QTextCursor.MoveOperation.End)

