    def set_workspace(self, path: str):
        self.workspace = Path(path)
        self.zip_payload = None
        self._parse_config()

    def _parse_config(self):
        if not self.workspace: return
        cfg = self.workspace / "src/source/Services/Config.bs"
        if cfg.exists():
            txt = cfg.read_text(errors="ignore")
            # Extract TMDB Key
            m = re.search(r'TMDB_KEY:\s*"([^"]+)"', txt)
            if m: self.tmdb_key = m.group(1)
            # Extract Servers
            self.servers = re.findall(
                r'id:\s*"([^"]+)".*?name:\s*"([^"]+)".*?movieBase:\s*"([^"]+)"',
                txt, re.S)

    # --- BUILD & PACKAGE ---
    def transpile_bsc(self):
        if not self.workspace: raise Exception("No Workspace Mounted.")
        if not (self.workspace / "node_modules").exists():
            subprocess.run(["npm", "install"], cwd=self.workspace, shell=True)
        res = subprocess.run(["npx", "bsc"],
                             cwd=self.workspace,
                             capture_output=True,
                             text=True,
                             shell=True)
        if res.returncode != 0:
            raise Exception("Transpiler Crushed:\n" + res.stdout[-1500:])
        return "Bytecode Transpilation Complete."

    def package_zip(self, minify=False, obfuscate=False):
        if not self.workspace: raise Exception("No Workspace Mounted.")
        base = self.workspace / "out/.roku-deploy-staging"
        if not base.exists(): base = self.workspace / "src"

        out_target = self.workspace / f"BingeBox-Quantum-{datetime.now().strftime('%H%M%S')}.zip"

        with zipfile.ZipFile(out_target,
                             "w",
                             zipfile.ZIP_DEFLATED,
                             compresslevel=9) as zf:
            for f in base.rglob("*"):
                if f.is_file():
                    data = f.read_bytes()
                    if f.suffix in [".bs", ".brs", ".xml"]:
                        txt = data.decode(errors="ignore")
                        if minify:
                            txt = re.sub(r"'.*$", "", txt,
                                         flags=re.M)  # Remove comments
                            txt = re.sub(r"^\s+", "", txt,
                                         flags=re.M)  # Remove indent spaces
                        if obfuscate and f.suffix != ".xml":
                            # Extremely basic variable mangling simulation
                            txt = re.sub(r'\bm\.', 'm.', txt)
                        data = txt.encode("utf-8")
                    zf.writestr(
                        str(f.relative_to(base)).replace("\\", "/"), data)

        self.zip_payload = out_target
        return f"Payload Locked: {out_target.name} ({out_target.stat().st_size//1024} KB)"

    # --- DEPLOY ---
    def deploy_to_target(self, ip: str, pwd: str, deep_launch: bool = False):
        if not self.zip_payload and self.workspace:
            self.transpile_bsc()
            self.package_zip()
        if not self.zip_payload: raise Exception("No Zip Payload Generated.")

