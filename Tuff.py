    # --- TMDB & SCRAPING ---
    def tmdb_search(self, query):
        url = f"{self.TMDB_BASE}/search/multi?api_key={self.tmdb_key}&query={urllib.parse.quote(query)}"
        with urllib.request.urlopen(url, timeout=5) as r:
            return json.loads(r.read().decode())

    def download_tmdb_assets(self,
                             target_id,
                             mtype="movie",
                             out_dir=None,
                             worker_signals=None):
        if not self.workspace and not out_dir:
            raise Exception("Set output dir or mount workspace.")
        dest = Path(
            out_dir
        ) if out_dir else self.workspace / f"TMDB_{target_id}_Assets"
        dest.mkdir(parents=True, exist_ok=True)

        url = f"{self.TMDB_BASE}/{mtype}/{target_id}/images?api_key={self.tmdb_key}"
        with urllib.request.urlopen(url) as r:
            data = json.loads(r.read().decode())

        total = 0
        for p in data.get("posters", [])[:5]:
            path = dest / f"poster_{p['file_path'].strip('/')}"
            urllib.request.urlretrieve(
                f"https://image.tmdb.org/t/p/original{p['file_path']}", path)
            total += 1
            if worker_signals:
                worker_signals.log.emit(f"Downloaded: {path.name}", "info")

        for b in data.get("backdrops", [])[:5]:
            path = dest / f"backdrop_{b['file_path'].strip('/')}"
            urllib.request.urlretrieve(
                f"https://image.tmdb.org/t/p/original{b['file_path']}", path)
            total += 1
            if worker_signals:
                worker_signals.log.emit(f"Downloaded: {path.name}", "info")

        return f"Bulk Download Complete: {total} High-Res Assets extracted to {dest.name}"

    # --- NETWORK UTILS ---
    def scan_subnet(self, worker_signals=None):
        try:
            base_ip = ".".join(
                socket.gethostbyname(socket.gethostname()).split(".")[:3])
        except:
            base_ip = "192.168.1"

        found = []

        def check(i):
            ip = f"{base_ip}.{i}"
            try:
                c = http.client.HTTPConnection(ip, 8060, timeout=1.0)
                c.request("GET", "/query/device-info")
                r = c.getresponse().read().decode()
                name = re.search(r"<friendly-device-name>([^<]+)", r)
                nm = name.group(1) if name else 'Roku Device'
                found.append(f"{ip} - {nm}")
                if worker_signals:
                    worker_signals.log.emit(
                        f"[RADAR] Hardware Detected: {ip} -> {nm}", "success")
            except:
                pass

        threads = [
            threading.Thread(target=check, args=(i, )) for i in range(1, 255)
        ]
        for t in threads:
            t.start()
        for t in threads:
            t.join()
        return "\n".join(
            found) if found else "Radar Sweep Complete: No signatures found."

    def compare_zips(self, path_a, path_b):
        try:
            with zipfile.ZipFile(path_a) as a, zipfile.ZipFile(path_b) as b:
                sa, sb = set(a.namelist()), set(b.namelist())
                added = sb - sa
                removed = sa - sb

                report = [
                    f"--- DELTA ANALYSIS: {Path(path_a).name} vs {Path(path_b).name} ---"
                ]
                if added: report.append(f"[+] ADDED: {', '.join(added)}")
                if removed: report.append(f"[-] REMOVED: {', '.join(removed)}")

                modified = []
                for f in sa & sb:
                    if a.getinfo(f).CRC != b.getinfo(f).CRC:
                        modified.append(
                            f"{f} (Diff: {b.getinfo(f).file_size - a.getinfo(f).file_size}b)"
                        )
                if modified:
                    report.append(f"[~] MODIFIED:\n  " + "\n  ".join(modified))

                if len(report) == 1:
                    report.append("Binaries are 100% Identical.")
                return "\n".join(report)
        except Exception as e:
            return f"Delta Calculation Failed: {str(e)}"


