    def _toggle_telnet(self):
        if self.telnet_socket:
            self.telnet_socket.close()
            self.telnet_socket = None
            self.log_msg("Telnet Socket Closed.", "warn")
            return

        ip = self.inp_ip.text()
        self.out_telnet.setText(f"Binding TCP link to {ip}:8085...\n")

        def _listen(worker_signals):
            self.telnet_socket = socket.socket(socket.AF_INET,
                                               socket.SOCK_STREAM)
            self.telnet_socket.settimeout(2.0)
            try:
                self.telnet_socket.connect((ip, 8085))
                worker_signals.log.emit("Telnet Datastream 8085 Active",
                                        "success")
                while self.telnet_socket:
                    try:
                        data = self.telnet_socket.recv(4096)
                        if not data: break
                        # We use pyqtSignal mapping via a small hack for UI safety in this blocking loop
                        # Normally we shouldn't update UI directly from thread, but QTextEdit append() is thread-safe in PyQt6
                        msg = data.decode(errors='ignore')
                        self.out_telnet.append(msg.strip())
                    except socket.timeout:
                        continue
            except Exception as e:
                if self.telnet_socket:
                    worker_signals.log.emit(f"Telnet Disturbance: {e}",
                                            "error")
            finally:
                self.telnet_socket = None

        # Fire and forget thread for telnet
        t = WorkerThread(_listen)
        t.signals.log.connect(self.log_msg)
        self._telnet_t = t
        t.start()

